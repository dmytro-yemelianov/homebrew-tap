  on_macos do
    if Hardware::CPU.intel?
      url "https://github.com/dmytro-yemelianov/raps/releases/download/v#{version}/raps-cli-x86_64-apple-darwin.tar.xz"
      sha256 "758802ce0c3da05c797911abb8fe73fc5a56ea20fcadb343d65a19b03b009b2d"
